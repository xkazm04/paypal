//! `bindings/dealStates.ts`: table-core's deal-state predicates as sets, so the windows and the
//! browser mock read the same classification Rust runs on instead of copying it. Each set is
//! [`DealState::ALL`] filtered by one predicate; table-core pins the predicates to the
//! `transition()` graph.
use table_core::DealState;

/// One exported set: its name, its doc line and the predicate that keeps its states.
type Set = (&'static str, &'static str, fn(DealState) -> bool);
/// Every exported set, in output order.
const SETS: [Set; 13] = [
    (
        "TERMINAL",
        "`DealState::terminal()`: the deal has ended; nothing moves it again but a statement match, a refund or a dispute.",
        DealState::terminal,
    ),
    (
        "PRE_CAPTURE",
        "`DealState::pre_capture()`: no money has been collected yet.",
        DealState::pre_capture,
    ),
    (
        "WITHDRAWABLE",
        "`DealState::withdrawable()`: where `transition(s, Withdraw)` is accepted (a held authorization is voided instead).",
        DealState::withdrawable,
    ),
    (
        "RELEASED",
        "`DealState::RELEASED`: the deal frees its budget; it never agreed, or was given back unpaid.",
        DealState::is_released,
    ),
    (
        "AGREED_OR_LATER",
        "`DealState::is_agreed_or_later()`: the forward chain from AGREED on, released states excluded.",
        DealState::is_agreed_or_later,
    ),
    (
        "THROUGH_AGREED",
        "`DealState::through_agreed()`: reached only through AGREED, released ones included; an agreement was recorded.",
        DealState::through_agreed,
    ),
    (
        "BEFORE_SETTLEMENT",
        "`DealState::before_settlement()`: PAIRING to AGREED; the band can still move and a seller deal is still watched.",
        DealState::before_settlement,
    ),
    (
        "OPEN_TABLE",
        "`DealState::open_table()`: still being talked, no agreement; a group close or open reaches it.",
        DealState::open_table,
    ),
    (
        "COUNTERSIGNABLE",
        "`DealState::countersignable()`: where the owner's countersign is accepted.",
        DealState::countersignable,
    ),
    (
        "QUIT_PENDING",
        "`DealState::quit_pending()`: the states the quit confirm lists on state alone.",
        DealState::quit_pending,
    ),
    (
        "ORDER_EXPECTED",
        "`DealState::order_expected()`: the checklist expects a PayPal order here.",
        DealState::order_expected,
    ),
    (
        "COMMITTED",
        "`DealState::is_committed()`: the exposure fold counts the money as committed.",
        DealState::is_committed,
    ),
    (
        "PAID",
        "`DealState::is_paid()`: the exposure fold counts the money as paid (UNCONFIRMED included).",
        DealState::is_paid,
    ),
];

pub fn typescript() -> Result<String, serde_json::Error> {
    let mut out = String::from(
        "// Generated by `cargo run -p table-client --bin generate-bindings` from table_core::DealState's\n\
         // predicates. Do not edit: change them in Rust.\n\
         import type { DealState } from \"./DealState\";\n",
    );
    for (name, doc, keep) in SETS {
        let states = DealState::ALL
            .into_iter()
            .filter(|s| keep(*s))
            .map(|s| serde_json::to_string(&s))
            .collect::<Result<Vec<_>, _>>()?
            .join(", ");
        out.push_str(&format!(
            "\n/** {doc} */\nexport const {name}: ReadonlySet<DealState> = new Set<DealState>([{states}]);\n"
        ));
    }
    Ok(out)
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use table_core::DealState;

    #[test]
    fn every_set_lists_exactly_the_states_its_predicate_keeps() {
        let ts = super::typescript().unwrap();
        for (name, _, keep) in super::SETS {
            let line = ts
                .lines()
                .find(|l| l.starts_with(&format!("export const {name}: ")))
                .unwrap();
            for state in DealState::ALL {
                let quoted = serde_json::to_string(&state).unwrap();
                assert_eq!(line.contains(&quoted), keep(state), "{name} {quoted}");
            }
        }
    }
}
