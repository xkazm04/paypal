const plural = (n: number, one: string, many = `${one}s`): string => `${n} ${n === 1 ? one : many}`;

/** "Refurbished 27-inch 4K monitor" -> "the refurbished 27-inch 4K monitor" (only a plain capitalised first word is lowered). */
export const tablesItem = (title: string): string => `the ${/^[A-Z][a-z]/.test(title) ? title.charAt(0).toLowerCase() + title.slice(1) : title}`;
/** "Dan" from "Dan · north-desk"; the house seller by its name. */
export const tablesShortWho = (c: { house?: boolean; name: string }): string => (c.house ? 'House seller' : c.name.split(' · ')[0] ?? c.name);
/** A long item title cut at a word for an answer line ("…" at the end); the full title is one level down. */
export const tablesClip = (s: string, max = 52): string => {
  if (s.length <= max) return s;
  const cut = s.slice(0, max);
  const sp = cut.lastIndexOf(' ');
  return `${(sp > max * 0.6 ? cut.slice(0, sp) : cut).replace(/[\s,;:(·–-]+$/, '')}…`;
};
